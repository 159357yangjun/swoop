#!/usr/bin/env python3
"""Real packaged Windows HLS -> FFmpeg -> final MP4 E2E.

Uses real Native Messaging length frames and GUI IPC (never a mocked state),
a private local HTTP server, and deterministic video/audio HLS playlists
generated by actual FFmpeg. Checks default/selected variant, decoded output,
failure propagation, and one-shot task submission. No public network URLs.
"""
from __future__ import annotations

import argparse
import functools
import hashlib
import http.server
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import threading
import time

from native_host_failure_e2e import host_call


class FixtureHandler(http.server.SimpleHTTPRequestHandler):
    def do_GET(self):
        self.server.requests.append(self.path)
        if self.path.split("?", 1)[0] == "/delayed/seg001.ts":
            self.server.slow_segment_requested.set()
            if not self.server.slow_segment_release.wait(timeout=25):
                raise AssertionError("Delayed segment was never released by test")
        super().do_GET()

    def log_message(self, *_args):
        return


def run(args: list[str], *, timeout: float = 45) -> subprocess.CompletedProcess:
    return subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, timeout=timeout, check=True)


def build_fixture(ffmpeg: str, root: Path) -> None:
    for name, dims, frequency in (("low", "160x96", 500), ("high", "320x192", 880)):
        target = root / name
        target.mkdir()
        run([ffmpeg, "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
             "-f", "lavfi", "-i", f"testsrc2=size={dims}:rate=10",
             "-f", "lavfi", "-i", f"sine=frequency={frequency}:sample_rate=48000",
             "-t", "3", "-c:v", "libx264", "-preset", "ultrafast",
             "-pix_fmt", "yuv420p", "-g", "10", "-c:a", "aac",
             "-b:a", "64k", "-f", "hls", "-hls_time", "1",
             "-hls_playlist_type", "vod", "-hls_flags", "independent_segments",
             "-hls_segment_filename", str(target / "seg%03d.ts"),
             str(target / "index.m3u8")], timeout=45)
        if len(list(target.glob("seg*.ts"))) < 2:
            raise AssertionError(f"HLS fixture did not produce multiple segments: {target}")
    (root / "master.m3u8").write_text(
        "#EXTM3U\n#EXT-X-VERSION:3\n"
        "#EXT-X-STREAM-INF:BANDWIDTH=200000,RESOLUTION=160x96\nlow/index.m3u8\n"
        "#EXT-X-STREAM-INF:BANDWIDTH=800000,RESOLUTION=320x192\nhigh/index.m3u8\n",
        encoding="utf-8",
    )
    # A deterministic publishing race: FFmpeg starts downloading, then the
    # E2E creates the final filename while a real TS request is blocked.
    delayed = root / "delayed"
    delayed.mkdir()
    for segment in (root / "high").glob("seg*.ts"):
        shutil.copy2(segment, delayed / segment.name)
    playlist = (root / "high" / "index.m3u8").read_text(encoding="utf-8")
    (root / "late.m3u8").write_text(
        "\n".join(("delayed/" + line if line.startswith("seg") and
                    line.endswith(".ts") else line) for line in playlist.splitlines()) + "\n",
        encoding="utf-8")
    (root / "broken.m3u8").write_text(
        "#EXTM3U\n#EXT-X-VERSION:3\n#EXT-X-TARGETDURATION:2\n"
        "#EXTINF:2.0,\nmissing.ts\n#EXT-X-ENDLIST\n", encoding="utf-8"
    )


def wait_gui(host: Path, dist: Path, proc: subprocess.Popen) -> None:
    deadline = time.monotonic() + 45
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise AssertionError(f"Packaged GUI exited unexpectedly rc={proc.returncode}")
        try:
            ping = host_call(host, dist, {"action": "ping"}, timeout=5)
            if ping.get("success") is True:
                return
        except (OSError, AssertionError):
            pass
        time.sleep(0.6)
    raise AssertionError("Packaged GUI IPC did not become ready within 45s")


def submit_once(host: Path, dist: Path, url: str, name: str,
                output_dir: Path, variant: str = "") -> tuple[int, str]:
    # The Native Host may have accepted the request even if a reply is lost:
    # no automatic retry of the add_download operation.
    response = host_call(host, dist, {
        "action": "add_download", "url": url, "filename": name,
        "saveDir": str(output_dir), "queue": "", "format": variant
    }, timeout=18)
    task_id = response.get("taskId")
    session = response.get("sessionId")
    if response.get("success") is not True or type(task_id) is not int or task_id <= 0:
        raise AssertionError(f"No confirmed HLS task ID for {name}: {response!r}")
    if not isinstance(session, str) or len(session) < 32:
        raise AssertionError(f"No HLS GUI session ID for {name}: {response!r}")
    return task_id, session


def poll_terminal(host: Path, dist: Path, task_id: int,
                  session: str, timeout: float = 85) -> dict:
    end = time.monotonic() + timeout
    last: dict = {}
    while time.monotonic() < end:
        last = host_call(host, dist, {
            "action": "get_task_status", "taskId": task_id,
            "sessionId": session
        }, timeout=10)
        if last.get("success") is True:
            if last.get("taskId") != task_id or last.get("sessionId") != session:
                raise AssertionError(f"HLS task identity changed: {last!r}")
            if last.get("state") in (3, 4, 5):
                return last
        time.sleep(0.4)
    raise AssertionError(f"HLS task never reached a terminal state: {last!r}")


def inspect_mp4(ffprobe: str, ffmpeg: str, root: Path,
                name: str, width: int, height: int,
                source_playlist: Path) -> tuple[Path, float]:
    paths = list(root.rglob(name))
    if len(paths) != 1:
        raise AssertionError(f"Expected exactly one final {name}, found {paths!r}")
    output = paths[0]
    if output.stat().st_size < 2048:
        raise AssertionError(f"HLS final file suspiciously small: {output}")
    raw = run([ffprobe, "-v", "error", "-show_entries",
               "stream=codec_name,codec_type,width,height",
               "-show_entries", "format=duration", "-of", "json",
               str(output)], timeout=20).stdout
    info = json.loads(raw)
    streams = info.get("streams", [])
    videos = [s for s in streams if s.get("codec_type") == "video"]
    audios = [s for s in streams if s.get("codec_type") == "audio"]
    if len(videos) != 1 or len(audios) != 1:
        raise AssertionError(f"Missing HLS video/audio streams in {name}: {info!r}")
    if videos[0].get("width") != width or videos[0].get("height") != height:
        raise AssertionError(f"Wrong HLS bitrate/variant selected for {name}: {info!r}")
    duration = float(info.get("format", {}).get("duration", 0))
    if not 2.7 <= duration <= 3.5:
        raise AssertionError(f"Final HLS duration should be approximately 3s: {info!r}")
    # Decode all streams, not just probe a container header.
    run([ffmpeg, "-v", "error", "-xerror", "-nostdin", "-i",
         str(output), "-f", "null", "-"], timeout=25)
    # Container metadata and stream dimensions do not prove the *contents*
    # survived remux. Compare the decoded video pixel bytes with the selected
    # source playlist (independent of MP4 timestamps and container metadata).
    def decoded_sha256(video: Path) -> str:
        proc = subprocess.run(
            [ffmpeg, "-v", "error", "-xerror", "-nostdin", "-i",
             str(video), "-map", "0:v:0", "-pix_fmt", "yuv420p",
             "-f", "rawvideo", "-"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=25, check=True)
        if not proc.stdout:
            raise AssertionError(f"No decoded frames from {video}")
        return hashlib.sha256(proc.stdout).hexdigest()
    if decoded_sha256(output) != decoded_sha256(source_playlist):
        raise AssertionError(f"Decoded frames differ from HLS source for {name}")
    return output, duration


def main() -> int:
    if os.name != "nt":
        raise SystemExit("This test requires packaged Windows GUI and Native Host")
    parser = argparse.ArgumentParser()
    parser.add_argument("--dist", required=True)
    args = parser.parse_args()
    dist = Path(args.dist).resolve()
    gui, host = dist / "idm-next.exe", dist / "idm-next-host.exe"
    if not gui.is_file() or not host.is_file():
        raise AssertionError("Packaged HLS GUI/Native Host binaries not found")
    ffmpeg = shutil.which("ffmpeg")
    ffprobe = shutil.which("ffprobe")
    if not ffmpeg or not ffprobe:
        raise AssertionError("Real FFmpeg and FFprobe are required; test may not silently skip")

    with tempfile.TemporaryDirectory(prefix="idm-hls-real-e2e-") as folder:
        scratch = Path(folder)
        public, output_dir = scratch / "media", scratch / "downloads"
        public.mkdir()
        output_dir.mkdir()
        build_fixture(ffmpeg, public)

        handler = functools.partial(FixtureHandler, directory=str(public))
        server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
        server.requests = []
        server.slow_segment_requested = threading.Event()
        server.slow_segment_release = threading.Event()
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        base = f"http://127.0.0.1:{server.server_port}"
        stdout_file, stderr_file = scratch / "gui.out", scratch / "gui.err"
        gui_out = stdout_file.open("wb")
        gui_err = stderr_file.open("wb")
        env = {**os.environ, "QT_LOGGING_TO_CONSOLE": "1"}
        env["PATH"] = str(Path(ffmpeg).parent) + os.pathsep + env.get("PATH", "")
        proc = subprocess.Popen([str(gui)], cwd=str(dist), stdin=subprocess.DEVNULL,
                                stdout=gui_out, stderr=gui_err, env=env)
        try:
            wait_gui(host, dist, proc)
            task_ids: set[int] = set()
            gui_session: str | None = None
            actual_final_dir: Path | None = None
            for filename, bandwidth, width, height in (
                ("automatic.mp4", "", 320, 192),
                ("low-choice.mp4", "200000", 160, 96),
            ):
                # Signed/query-string URL must be routed as HLS, NOT saved as
                # the raw text contents of the .m3u8 manifest.
                url = base + "/master.m3u8?token=local-test"
                task_id, session_id = submit_once(
                    host, dist, url, filename, output_dir, bandwidth)
                if task_id in task_ids:
                    raise AssertionError(f"Different HLS tasks reused one task ID: {task_id}")
                task_ids.add(task_id)
                if gui_session is not None and session_id != gui_session:
                    raise AssertionError("HLS GUI session changed between tasks")
                gui_session = session_id
                state = poll_terminal(host, dist, task_id, session_id)
                if state.get("state") != 3:
                    raise AssertionError(f"Expected completed HLS MP4, got {state!r}")
                chosen = "high" if not bandwidth else "low"
                output, duration = inspect_mp4(
                    ffprobe, ffmpeg, output_dir, filename, width, height,
                    public / chosen / "index.m3u8")
                if actual_final_dir is not None and output.parent != actual_final_dir:
                    raise AssertionError("Unexpected HLS archive destination changed")
                actual_final_dir = output.parent
                print(f"[PASS] real HLS: task={task_id} variant={bandwidth or 'highest'} "
                      f"size={output.stat().st_size} width={width} height={height} "
                      f"duration={duration:.3f}s decoded=true frame_sha256=match")
            assert actual_final_dir is not None
            def assert_no_staging_or_extra(name: str) -> None:
                leftovers = list(output_dir.rglob(".idm-next-hls-*"))
                if leftovers:
                    raise AssertionError(f"HLS staging was not cleaned: {leftovers!r}")
                results = list(output_dir.rglob(name))
                if len(results) != 1:
                    raise AssertionError(f"Expected exactly one protected {name}, got {results!r}")

            # Collision present BEFORE FFmpeg is launched: reject the download
            # without modifying the pre-existing user's file.
            existing = actual_final_dir / "already-there.mp4"
            sentinel = b"IDM-NEXT-DO-NOT-REPLACE-" * 47
            existing.write_bytes(sentinel)
            existing_sha = hashlib.sha256(existing.read_bytes()).hexdigest()
            occupied_id, occupied_session = submit_once(
                host, dist, base + "/master.m3u8", existing.name, output_dir)
            occupied = poll_terminal(host, dist, occupied_id, occupied_session)
            if occupied.get("state") != 4 or "已存在" not in str(occupied.get("error")):
                raise AssertionError(f"Preexisting output was not safely rejected: {occupied!r}")
            assert_no_staging_or_extra(existing.name)
            if hashlib.sha256(existing.read_bytes()).hexdigest() != existing_sha:
                raise AssertionError("Preexisting MP4 bytes were overwritten")
            print("[PASS] preexisting HLS output preserved; failed status and reason correct")

            # Collision DURING real FFmpeg download, after the playlist was
            # accepted, while the HTTP segment is deliberately held.
            late = actual_final_dir / "race-protected.mp4"
            server.slow_segment_requested.clear()
            server.slow_segment_release.clear()
            late_id, late_session = submit_once(
                host, dist, base + "/late.m3u8", late.name, output_dir)
            try:
                if not server.slow_segment_requested.wait(timeout=20):
                    raise AssertionError("FFmpeg did not request the delayed TS segment")
                late.write_bytes(sentinel)
                late_sha = hashlib.sha256(late.read_bytes()).hexdigest()
            finally:
                server.slow_segment_release.set()
            late_state = poll_terminal(host, dist, late_id, late_session)
            if late_state.get("state") != 4 or "已存在" not in str(late_state.get("error")):
                raise AssertionError(f"Late output collision was not safely rejected: {late_state!r}")
            assert_no_staging_or_extra(late.name)
            if hashlib.sha256(late.read_bytes()).hexdigest() != late_sha:
                raise AssertionError("Late-created user file was overwritten")
            print("[PASS] late HLS output race preserved original and removed stage")

            missing_id, missing_session = submit_once(
                host, dist, base + "/broken.m3u8",
                "broken.mp4", output_dir)
            if missing_id in task_ids or missing_session != gui_session:
                raise AssertionError("Failed HLS task reused another ID or GUI session changed")
            failure = poll_terminal(host, dist, missing_id, missing_session)
            if failure.get("state") != 4:
                raise AssertionError(f"Missing HLS segment must fail: {failure!r}")
            if not isinstance(failure.get("error"), str) or not failure["error"].strip():
                raise AssertionError(f"HLS failure reason missing from GUI IPC: {failure!r}")
            if list(output_dir.rglob("broken.mp4")):
                raise AssertionError("Failed HLS stream exposed a partial final MP4")
            if list(output_dir.rglob(".idm-next-hls-*")):
                raise AssertionError("Failed HLS stream left a staging directory")
            print(f"[PASS] missing HLS segment fails and propagates reason: "
                  f"task={missing_id} state=4 error_present=true")
            for required in ("/master.m3u8", "/high/index.m3u8",
                             "/low/index.m3u8", "/late.m3u8",
                             "/delayed/seg001.ts", "/broken.m3u8", "/missing.ts"):
                if not any(r.split("?")[0] == required for r in server.requests):
                    raise AssertionError(f"HTTP server never observed {required!r}")
            print("[PASS] real HLS manifests, selected variants and missing segment "
                  "all reached the local server")
            return 0
        finally:
            if proc.poll() is None:
                proc.terminate()
                try:
                    proc.wait(timeout=8)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait()
            gui_out.close()
            gui_err.close()
            if sys.exc_info()[0] is not None:
                print("[GUI STDERR TAIL]", stderr_file.read_text(
                    encoding="utf-8", errors="replace")[-3500:], file=sys.stderr)
            server.shutdown()
            server.server_close()


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:
        print("[FAIL] Real packaged HLS/FFmpeg E2E:", repr(exc), file=sys.stderr)
        sys.exit(1)
