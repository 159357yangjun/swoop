    inline static constexpr quint8 s_rcon[11] = {
        0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
    };

    quint8 m_rk[11][16];  // 轮密钥（列主序：列 c 占字节 4c..4c+3）

    static quint8 gmul(quint8 a, quint8 b) {
        quint8 p = 0;
        for (int i = 0; i < 8; ++i) {
            if (b & 1) p ^= a;
            quint8 hi = static_cast<quint8>(a & 0x80);
            a = static_cast<quint8>(a << 1);
            if (hi) a ^= 0x1b;
            b = static_cast<quint8>(b >> 1);
        }
        return p;
    }

    void keyExpansion(const quint8 key[16]) {
        std::memcpy(m_rk[0], key, 16);
        for (int i = 1; i <= 10; ++i) {
            quint8 temp[4];
            std::memcpy(temp, &m_rk[i-1][12], 4);          // 上一轮最后一个字
            quint8 t = temp[0]; temp[0]=temp[1]; temp[1]=temp[2]; temp[2]=temp[3]; temp[3]=t; // RotWord
            for (int j = 0; j < 4; ++j) temp[j] = s_sbox[temp[j]];                            // SubWord
            temp[0] ^= s_rcon[i];
            for (int j = 0; j < 4; ++j)
                m_rk[i][j] = static_cast<quint8>(m_rk[i-1][j] ^ temp[j]);
            for (int c = 1; c < 4; ++c)
                for (int j = 0; j < 4; ++j)
                    m_rk[i][4*c+j] = static_cast<quint8>(m_rk[i][4*(c-1)+j] ^ m_rk[i-1][4*c+j]);
        }
    }

    void addRoundKey(quint8 s[16], int round) const {
        for (int i = 0; i < 16; ++i)
            s[i] = static_cast<quint8>(s[i] ^ m_rk[round][i]);
    }
    void subBytes(quint8 s[16]) const {
        for (int i = 0; i < 16; ++i) s[i] = s_sbox[s[i]];
    }
    void invSubBytes(quint8 s[16]) const {
        for (int i = 0; i < 16; ++i) s[i] = s_invSbox[s[i]];
    }
    void shiftRows(quint8 s[16]) const {
        for (int r = 1; r < 4; ++r) {
            quint8 row[4] = { s[r], s[r+4], s[r+8], s[r+12] };
            quint8 t[4];
            for (int c = 0; c < 4; ++c) t[c] = row[(c+r)%4];
            s[r]=t[0]; s[r+4]=t[1]; s[r+8]=t[2]; s[r+12]=t[3];
        }
    }
    void invShiftRows(quint8 s[16]) const {
        for (int r = 1; r < 4; ++r) {
            quint8 row[4] = { s[r], s[r+4], s[r+8], s[r+12] };
            quint8 t[4];
            for (int c = 0; c < 4; ++c) t[c] = row[(c-r+4)%4];
            s[r]=t[0]; s[r+4]=t[1]; s[r+8]=t[2]; s[r+12]=t[3];
        }
    }
    void mixColumns(quint8 s[16]) const {
        for (int c = 0; c < 4; ++c) {
            int o = 4*c;
            quint8 a0=s[o],a1=s[o+1],a2=s[o+2],a3=s[o+3];
            s[o]   = static_cast<quint8>(gmul(a0,2)^gmul(a1,3)^a2^a3);
            s[o+1] = static_cast<quint8>(a0^gmul(a1,2)^gmul(a2,3)^a3);
            s[o+2] = static_cast<quint8>(a0^a1^gmul(a2,2)^gmul(a3,3));
            s[o+3] = static_cast<quint8>(gmul(a0,3)^a1^a2^gmul(a3,2));
        }
    }
    void invMixColumns(quint8 s[16]) const {
        for (int c = 0; c < 4; ++c) {
            int o = 4*c;
            quint8 a0=s[o],a1=s[o+1],a2=s[o+2],a3=s[o+3];
            s[o]   = static_cast<quint8>(gmul(a0,14)^gmul(a1,11)^gmul(a2,13)^gmul(a3,9));
            s[o+1] = static_cast<quint8>(gmul(a0,9)^gmul(a1,14)^gmul(a2,11)^gmul(a3,13));
            s[o+2] = static_cast<quint8>(gmul(a0,13)^gmul(a1,9)^gmul(a2,14)^gmul(a3,11));
            s[o+3] = static_cast<quint8>(gmul(a0,11)^gmul(a1,13)^gmul(a2,9)^gmul(a3,14));
        }
    }

    void decryptBlock(const quint8 in[16], quint8 out[16]) const {
        quint8 st[16];
        std::memcpy(st, in, 16);
        addRoundKey(st, 10);
        for (int r = 9; r >= 1; --r) {
            invShiftRows(st);
            invSubBytes(st);
            addRoundKey(st, r);
            invMixColumns(st);
        }
        invShiftRows(st);
        invSubBytes(st);
        addRoundKey(st, 0);
        std::memcpy(out, st, 16);
    }
